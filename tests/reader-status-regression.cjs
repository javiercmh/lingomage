const fs = require('node:fs'), vm = require('node:vm'), assert = require('node:assert/strict');
const source = fs.readFileSync('js/app.js', 'utf8');
const elements = new Map();
const element = id => { if (!elements.has(id)) elements.set(id, { hidden: false, disabled: false, textContent: '' }); return elements.get(id); };
const context = {state: { readerId: 'story', pendingReaderResult: null }, $: element, readerPanel: () => ({classList: {toggle(){}}}), document: {querySelector: () => ({})}};
vm.createContext(context);
vm.runInContext(source.slice(source.indexOf('let readerGeneration'), source.indexOf("$('reader-generation-dismiss').addEventListener")), context);
context.setReaderGeneration({storyId: 'story', phase: 'working', message: 'Writing…'});
assert.equal(element('reader-generation-bar').hidden, false);
assert.equal(element('reader-generation-action').textContent, 'Cancel request');
context.state.readerId = 'other'; context.renderReaderGeneration();
assert.equal(element('reader-generation-bar').hidden, true);
context.state.readerId = 'story';
context.state.pendingReaderResult = {story: {id: 'story'}, saved: false}; context.renderReaderGeneration();
assert.equal(element('reader-generation-action').textContent, 'Save response');
context.state.pendingReaderResult.saved = true; context.renderReaderGeneration();
assert.equal(element('reader-generation-action').textContent, 'Finish request');
context.state.pendingReaderResult = null;
context.setReaderGeneration({storyId: 'story', phase: 'ready', message: 'Ready'});
assert.equal(element('reader-generation-action').textContent, 'View result');
assert.equal(element('reader-generation-dismiss').hidden, false);
context.setReaderGeneration({storyId: 'story', phase: 'error', message: 'Failed'});
assert.equal(element('reader-generation-action').hidden, true);
assert.equal(element('reader-generation-message').textContent, 'Failed');
context.setReaderGeneration(null); assert.equal(element('reader-generation-bar').hidden, true);
console.log('PASS floating status: working, story association, save/release recovery, ready, error and dismissal');
